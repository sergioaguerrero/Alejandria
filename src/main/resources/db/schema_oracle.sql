-- 4. REPOSITORIO DE RECURSOS ACADÉMICOS (DOCUMENTOS)
-- ============================================================================

CREATE TABLE RECURSO_ACADEMICO (
    id              NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titulo          VARCHAR2(200 CHAR)                      NOT NULL,
    descripcion     VARCHAR2(2000 CHAR),
    tipo_recurso    VARCHAR2(20 CHAR)                       NOT NULL,
    corte           NUMBER(10, 0)     DEFAULT 1             NOT NULL,
    tema            VARCHAR2(80 CHAR),
    nombre_archivo  VARCHAR2(255 CHAR),
    archivo_bytes   BLOB                                    NOT NULL,
    tipo_mime       VARCHAR2(100 CHAR)                      NOT NULL,
    tamano_bytes    NUMBER(19, 0)                           NOT NULL,
    fecha_subida    TIMESTAMP(6)      DEFAULT LOCALTIMESTAMP NOT NULL,
    estado          VARCHAR2(20 CHAR)                       NOT NULL,
    total_vistas    NUMBER(10, 0)     DEFAULT 0             NOT NULL,
    total_descargas NUMBER(10, 0)     DEFAULT 0             NOT NULL,
    subido_por      NUMBER(19, 0)                           NOT NULL,
    materia_id      NUMBER(19, 0)                           NOT NULL,
    repositorio_id  NUMBER(19, 0),
    CONSTRAINT pk_recurso_academico   PRIMARY KEY (id),
    CONSTRAINT chk_recurso_tipo       CHECK (tipo_recurso IN ('NOTE', 'SUMMARY', 'GUIDE', 'WORKSHOP', 'PROJECT')),
    CONSTRAINT chk_recurso_corte      CHECK (corte IN (1, 2, 3)),
    CONSTRAINT chk_recurso_estado     CHECK (estado IN ('PENDING', 'PUBLISHED', 'REPORTED', 'HIDDEN', 'REMOVED')),
    CONSTRAINT fk_recurso_subido_por  FOREIGN KEY (subido_por)     REFERENCES USUARIO (id),
    CONSTRAINT fk_recurso_materia     FOREIGN KEY (materia_id)     REFERENCES MATERIA (id),
    CONSTRAINT fk_recurso_repositorio FOREIGN KEY (repositorio_id) REFERENCES REPOSITORIO_ESTUDIO (id) ON DELETE CASCADE
);

CREATE INDEX idx_recurso_subido_por  ON RECURSO_ACADEMICO (subido_por);
CREATE INDEX idx_recurso_materia     ON RECURSO_ACADEMICO (materia_id);
CREATE INDEX idx_recurso_repositorio ON RECURSO_ACADEMICO (repositorio_id);
CREATE INDEX idx_recurso_corte       ON RECURSO_ACADEMICO (corte);
CREATE INDEX idx_recurso_tema        ON RECURSO_ACADEMICO (tema);

CREATE TABLE ETIQUETA (
    id     NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR2(30 CHAR) NOT NULL,
    CONSTRAINT pk_etiqueta        PRIMARY KEY (id),
    CONSTRAINT uq_etiqueta_nombre UNIQUE (nombre)
);

CREATE TABLE RECURSO_ETIQUETA (
    recurso_id  NUMBER(19, 0) NOT NULL,
    etiqueta_id NUMBER(19, 0) NOT NULL,
    CONSTRAINT pk_recurso_etiqueta  PRIMARY KEY (recurso_id, etiqueta_id),
    CONSTRAINT fk_rec_etiq_recurso  FOREIGN KEY (recurso_id)  REFERENCES RECURSO_ACADEMICO (id) ON DELETE CASCADE,
    CONSTRAINT fk_rec_etiq_etiqueta FOREIGN KEY (etiqueta_id) REFERENCES ETIQUETA (id)          ON DELETE CASCADE
);

CREATE INDEX idx_rec_etiq_etiqueta ON RECURSO_ETIQUETA (etiqueta_id);

-- ============================================================================
-- 5. GOBERNANZA, MODERACIÓN Y AUDITORÍA
-- ============================================================================

CREATE TABLE REPORTE (
    id                  NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    motivo              VARCHAR2(30 CHAR)                      NOT NULL,
    descripcion         VARCHAR2(1000 CHAR),
    fecha_reporte       TIMESTAMP(6)  DEFAULT LOCALTIMESTAMP   NOT NULL,
    estado              VARCHAR2(20 CHAR)                      NOT NULL,
    tipo_objetivo       VARCHAR2(20 CHAR)  DEFAULT 'DOCUMENT'  NOT NULL,
    etiqueta_objetivo   VARCHAR2(255 CHAR),
    reportante_id       NUMBER(19, 0)                          NOT NULL,
    recurso_id          NUMBER(19, 0),
    repositorio_id      NUMBER(19, 0),
    usuario_objetivo_id NUMBER(19, 0),
    moderador_id        NUMBER(19, 0),
    CONSTRAINT pk_reporte             PRIMARY KEY (id),
    CONSTRAINT chk_reporte_motivo     CHECK (motivo IN ('ACTIVE_EXAM', 'PLAGIARISM', 'INAPPROPRIATE_CONTENT', 'CORRUPTED_FILE', 'MISLABELED', 'DUPLICATE', 'OTHER')),
    CONSTRAINT chk_reporte_estado     CHECK (estado IN ('OPEN', 'UNDER_REVIEW', 'RESOLVED', 'DISMISSED')),
    CONSTRAINT chk_reporte_tipo_obj   CHECK (tipo_objetivo IN ('DOCUMENT', 'REPOSITORY', 'PROFILE')),
    CONSTRAINT fk_reporte_reportante  FOREIGN KEY (reportante_id)       REFERENCES USUARIO (id),
    CONSTRAINT fk_reporte_recurso     FOREIGN KEY (recurso_id)          REFERENCES RECURSO_ACADEMICO (id) ON DELETE SET NULL,
    CONSTRAINT fk_reporte_repositorio FOREIGN KEY (repositorio_id)      REFERENCES REPOSITORIO_ESTUDIO (id) ON DELETE SET NULL,
    CONSTRAINT fk_reporte_usuario_obj FOREIGN KEY (usuario_objetivo_id) REFERENCES USUARIO (id) ON DELETE SET NULL,
    CONSTRAINT fk_reporte_moderador   FOREIGN KEY (moderador_id)        REFERENCES USUARIO (id)
);

CREATE INDEX idx_reporte_estado      ON REPORTE (estado);
CREATE INDEX idx_reporte_recurso     ON REPORTE (recurso_id);
CREATE INDEX idx_reporte_repositorio ON REPORTE (repositorio_id);
CREATE INDEX idx_reporte_usuario_obj ON REPORTE (usuario_objetivo_id);
CREATE INDEX idx_reporte_reportante  ON REPORTE (reportante_id);
CREATE INDEX idx_reporte_moderador   ON REPORTE (moderador_id);

CREATE TABLE DECISION (
    id                NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    accion_moderacion VARCHAR2(30 CHAR)                     NOT NULL,
    justificacion     VARCHAR2(1000 CHAR),
    fecha_decision    TIMESTAMP(6)  DEFAULT LOCALTIMESTAMP  NOT NULL,
    reporte_id        NUMBER(19, 0)                         NOT NULL,
    moderador_id      NUMBER(19, 0)                         NOT NULL,
    CONSTRAINT pk_decision           PRIMARY KEY (id),
    CONSTRAINT uq_decision_reporte   UNIQUE (reporte_id),
    CONSTRAINT chk_decision_accion   CHECK (accion_moderacion IN ('KEEP', 'HIDE', 'REMOVE', 'WARN_USER', 'SUSPEND_USER')),
    CONSTRAINT fk_decision_reporte   FOREIGN KEY (reporte_id)   REFERENCES REPORTE (id),
    CONSTRAINT fk_decision_moderador FOREIGN KEY (moderador_id) REFERENCES USUARIO (id)
);

CREATE INDEX idx_decision_moderador ON DECISION (moderador_id);

CREATE TABLE SANCION_USUARIO (
    id             NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id     NUMBER(19, 0)                      NOT NULL,
    moderador_id   NUMBER(19, 0)                      NOT NULL,
    reporte_id     NUMBER(19, 0),
    tipo           VARCHAR2(20 CHAR)                  NOT NULL,
    motivo         VARCHAR2(300 CHAR)                 NOT NULL,
    nota           VARCHAR2(1000 CHAR),
    fecha_creacion TIMESTAMP(6)  DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_sancion_usuario    PRIMARY KEY (id),
    CONSTRAINT chk_sancion_tipo      CHECK (tipo IN ('ADVERTENCIA', 'SUSPENSION', 'REACTIVACION')),
    CONSTRAINT fk_sancion_usuario    FOREIGN KEY (usuario_id)   REFERENCES USUARIO (id) ON DELETE CASCADE,
    CONSTRAINT fk_sancion_moderador  FOREIGN KEY (moderador_id) REFERENCES USUARIO (id),
    CONSTRAINT fk_sancion_reporte    FOREIGN KEY (reporte_id)   REFERENCES REPORTE (id) ON DELETE SET NULL
);

CREATE INDEX idx_sancion_usuario_fecha ON SANCION_USUARIO (usuario_id, fecha_creacion DESC);

CREATE TABLE REGISTRO_AUDITORIA (
    id             NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_accion  VARCHAR2(100 CHAR)                     NOT NULL,
    nombre_entidad VARCHAR2(100 CHAR)                     NOT NULL,
    entidad_id     NUMBER(19, 0),
    fecha_evento   TIMESTAMP(6)  DEFAULT LOCALTIMESTAMP   NOT NULL,
    ip_origen      VARCHAR2(45 CHAR),
    usuario_id     NUMBER(19, 0),
    CONSTRAINT pk_registro_auditoria PRIMARY KEY (id),
    CONSTRAINT fk_auditoria_usuario  FOREIGN KEY (usuario_id) REFERENCES USUARIO (id)
);

CREATE INDEX idx_auditoria_usuario ON REGISTRO_AUDITORIA (usuario_id);
CREATE INDEX idx_auditoria_entidad ON REGISTRO_AUDITORIA (nombre_entidad, entidad_id);

-- ============================================================================
-- 6. NOTIFICACIONES Y ASISTENCIA CON INTELIGENCIA ARTIFICIAL
-- ============================================================================

CREATE TABLE NOTIFICACION (
    id             NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id     NUMBER(19, 0)                         NOT NULL,
    tipo           VARCHAR2(40 CHAR)                     NOT NULL,
    titulo         VARCHAR2(200 CHAR)                    NOT NULL,
    mensaje        VARCHAR2(1000 CHAR)                   NOT NULL,
    url_destino    VARCHAR2(500 CHAR),
    leida          NUMBER(1, 0)  DEFAULT 0               NOT NULL,
    fecha_creacion TIMESTAMP(6)  DEFAULT LOCALTIMESTAMP  NOT NULL,
    CONSTRAINT pk_notificacion PRIMARY KEY (id),
    CONSTRAINT chk_notif_tipo  CHECK (tipo IN (
        'NEW_CONTENT', 'WARNING', 'CONTENT_HIDDEN', 'CONTENT_DELETED',
        'SANCTION', 'LIKE', 'SYSTEM', 'REPORT_PENDING',
        'NEW_FOLLOWER', 'FRIEND_MATCH', 'AI_SHARED', 'COLLAB_INVITE'
    )),
    CONSTRAINT chk_notif_leida  CHECK (leida IN (0, 1)),
    CONSTRAINT fk_notif_usuario FOREIGN KEY (usuario_id) REFERENCES USUARIO (id) ON DELETE CASCADE
);

CREATE INDEX idx_notif_usuario_fecha ON NOTIFICACION (usuario_id, fecha_creacion DESC);
CREATE INDEX idx_notif_usuario_leida ON NOTIFICACION (usuario_id, leida);

CREATE TABLE MATERIAL_IA (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id         NUMBER(19, 0)                         NOT NULL,
    repositorio_id     NUMBER(19, 0),
    tipo_contenido     VARCHAR2(20 CHAR)                     NOT NULL,
    titulo             VARCHAR2(255 CHAR)                    NOT NULL,
    nombre_repositorio VARCHAR2(200 CHAR)                    NOT NULL,
    nombre_materia     VARCHAR2(200 CHAR)                    NOT NULL,
    alcance            VARCHAR2(20 CHAR)                     NOT NULL,
    valor_alcance      VARCHAR2(200 CHAR),
