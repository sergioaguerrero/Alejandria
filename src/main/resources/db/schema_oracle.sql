-- ============================================================================
-- 1. IDENTIDAD, CONTROL DE ACCESO Y PERFIL DE USUARIO
-- ============================================================================

CREATE TABLE ROL (
    id     NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT pk_rol        PRIMARY KEY (id),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

CREATE TABLE PERMISO_ROL (
    rol_id  NUMBER(19, 0)     NOT NULL,
    permiso VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT pk_permiso_rol     PRIMARY KEY (rol_id, permiso),
    CONSTRAINT fk_permiso_rol_rol FOREIGN KEY (rol_id) REFERENCES ROL (id) ON DELETE CASCADE
);

CREATE TABLE USUARIO (
    id                   NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_usuario       VARCHAR2(20 CHAR)                      NOT NULL,
    primer_nombre        VARCHAR2(20 CHAR)                      NOT NULL,
    segundo_nombre       VARCHAR2(20 CHAR),
    primer_apellido      VARCHAR2(20 CHAR)                      NOT NULL,
    segundo_apellido     VARCHAR2(20 CHAR)                      NOT NULL,
    correo_institucional VARCHAR2(80 CHAR)                      NOT NULL,
    contrasena_hash      VARCHAR2(70 CHAR)                      NOT NULL,
    verificado           NUMBER(1, 0)      DEFAULT 0            NOT NULL,
    suspendido           NUMBER(1, 0)      DEFAULT 0            NOT NULL,
    fecha_registro       TIMESTAMP(6)      DEFAULT LOCALTIMESTAMP NOT NULL,
    semestre             NUMBER(10, 0),
    descripcion          VARCHAR2(500 CHAR),
    rol_id               NUMBER(19, 0),
    CONSTRAINT pk_usuario             PRIMARY KEY (id),
    CONSTRAINT uq_usuario_nombre      UNIQUE (nombre_usuario),
    CONSTRAINT uq_usuario_correo      UNIQUE (correo_institucional),
    CONSTRAINT chk_usuario_verificado CHECK (verificado IN (0, 1)),
    CONSTRAINT chk_usuario_suspendido CHECK (suspendido IN (0, 1)),
    CONSTRAINT fk_usuario_rol         FOREIGN KEY (rol_id) REFERENCES ROL (id)
);

CREATE INDEX idx_usuario_rol ON USUARIO (rol_id);

CREATE TABLE CODIGO_VERIFICACION_CORREO (
    id               NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id       NUMBER(19, 0)                  NOT NULL,
    codigo_hash      VARCHAR2(128 CHAR)             NOT NULL,
    fecha_creacion   TIMESTAMP(6)                   NOT NULL,
    fecha_expiracion TIMESTAMP(6)                   NOT NULL,
    intentos         NUMBER(10, 0) DEFAULT 0        NOT NULL,
    usado            NUMBER(1, 0)  DEFAULT 0        NOT NULL,
    CONSTRAINT pk_codigo_verificacion PRIMARY KEY (id),
    CONSTRAINT chk_cvc_usado          CHECK (usado IN (0, 1)),
    CONSTRAINT fk_cvc_usuario         FOREIGN KEY (usuario_id) REFERENCES USUARIO (id) ON DELETE CASCADE
);

CREATE INDEX idx_cvc_usuario_usado    ON CODIGO_VERIFICACION_CORREO (usuario_id, usado);
CREATE INDEX idx_cvc_fecha_expiracion ON CODIGO_VERIFICACION_CORREO (fecha_expiracion);

CREATE TABLE TOKEN_RECUPERACION_CONTRASENA (
    id               NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id       NUMBER(19, 0)                  NOT NULL,
    token_hash       VARCHAR2(128 CHAR)             NOT NULL,
    fecha_creacion   TIMESTAMP(6)                   NOT NULL,
    fecha_expiracion TIMESTAMP(6)                   NOT NULL,
    usado            NUMBER(1, 0)  DEFAULT 0        NOT NULL,
    CONSTRAINT pk_token_recuperacion PRIMARY KEY (id),
    CONSTRAINT uq_trc_token_hash     UNIQUE (token_hash),
    CONSTRAINT chk_trc_usado         CHECK (usado IN (0, 1)),
    CONSTRAINT fk_trc_usuario        FOREIGN KEY (usuario_id) REFERENCES USUARIO (id) ON DELETE CASCADE
);

CREATE INDEX idx_trc_usuario_usado    ON TOKEN_RECUPERACION_CONTRASENA (usuario_id, usado);
CREATE INDEX idx_trc_fecha_expiracion ON TOKEN_RECUPERACION_CONTRASENA (fecha_expiracion);

CREATE TABLE SEGUIMIENTO_USUARIO (
    seguidor_id    NUMBER(19, 0)                    NOT NULL,
    seguido_id     NUMBER(19, 0)                    NOT NULL,
    fecha_registro TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_seguimiento_usuario PRIMARY KEY (seguidor_id, seguido_id),
    CONSTRAINT chk_seg_usr_no_self    CHECK (seguidor_id <> seguido_id),
    CONSTRAINT fk_seg_usr_seguidor    FOREIGN KEY (seguidor_id) REFERENCES USUARIO (id) ON DELETE CASCADE,
    CONSTRAINT fk_seg_usr_seguido     FOREIGN KEY (seguido_id)  REFERENCES USUARIO (id) ON DELETE CASCADE
);

CREATE INDEX idx_seg_usr_seguido ON SEGUIMIENTO_USUARIO (seguido_id);

CREATE TABLE CONTACTO_USUARIO (
    id         NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id NUMBER(19, 0)                      NOT NULL,
    tipo       VARCHAR2(30 CHAR)                  NOT NULL,
    valor      VARCHAR2(255 CHAR)                 NOT NULL,
    etiqueta   VARCHAR2(60 CHAR),
    orden      NUMBER(10, 0)     DEFAULT 0        NOT NULL,
    CONSTRAINT pk_contacto_usuario PRIMARY KEY (id),
    CONSTRAINT chk_contacto_tipo   CHECK (tipo IN (
        'EMAIL', 'WHATSAPP', 'INSTAGRAM', 'LINKEDIN', 'GITHUB', 'TELEGRAM', 'DISCORD', 'WEBSITE', 'OTHER'
    )),
    CONSTRAINT fk_contacto_usuario FOREIGN KEY (usuario_id) REFERENCES USUARIO (id) ON DELETE CASCADE
);

CREATE INDEX idx_contacto_usuario ON CONTACTO_USUARIO (usuario_id, orden);

