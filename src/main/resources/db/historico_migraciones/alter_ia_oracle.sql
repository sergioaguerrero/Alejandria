CREATE TABLE MATERIAL_IA (
    id                 NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id         NUMBER(19, 0)                      NOT NULL,
    repositorio_id     NUMBER(19, 0),
    tipo_contenido     VARCHAR2(20 CHAR)                  NOT NULL,
    titulo             VARCHAR2(255 CHAR)                 NOT NULL,
    nombre_repositorio VARCHAR2(200 CHAR)                 NOT NULL,
    nombre_materia     VARCHAR2(200 CHAR)                 NOT NULL,
    alcance            VARCHAR2(20 CHAR)                  NOT NULL,
    valor_alcance      VARCHAR2(200 CHAR),
    etiqueta_alcance   VARCHAR2(255 CHAR)                 NOT NULL,
    contenido_json     CLOB                               NOT NULL,
    guardado_estudio   NUMBER(1, 0)  DEFAULT 0            NOT NULL,
    ultima_puntuacion  NUMBER(10, 0),
    fecha_creacion     TIMESTAMP(6)  DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_material_ia      PRIMARY KEY (id),
    CONSTRAINT chk_mat_ia_tipo     CHECK (tipo_contenido IN ('QUIZ', 'SUMMARY', 'GUIDE', 'SLIDES')),
    CONSTRAINT chk_mat_ia_alcance  CHECK (alcance IN ('all', 'term', 'topic', 'tag')),
    CONSTRAINT chk_mat_ia_guardado CHECK (guardado_estudio IN (0, 1)),
    CONSTRAINT fk_mat_ia_usuario   FOREIGN KEY (usuario_id)     REFERENCES USUARIO (id)             ON DELETE CASCADE,
    CONSTRAINT fk_mat_ia_repo      FOREIGN KEY (repositorio_id) REFERENCES REPOSITORIO_ESTUDIO (id) ON DELETE SET NULL
);

CREATE INDEX idx_mat_ia_usuario_fecha ON MATERIAL_IA (usuario_id, fecha_creacion DESC);
CREATE INDEX idx_mat_ia_usuario_guard ON MATERIAL_IA (usuario_id, guardado_estudio, fecha_creacion DESC);
CREATE INDEX idx_mat_ia_repo          ON MATERIAL_IA (repositorio_id);

CREATE TABLE COMPARTIDO_IA (
    id               NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    material_id      NUMBER(19, 0)                      NOT NULL,
    remitente_id     NUMBER(19, 0)                      NOT NULL,
    destinatario_id  NUMBER(19, 0)                      NOT NULL,
    nota             VARCHAR2(500 CHAR),
    fecha_compartido TIMESTAMP(6)  DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_compartido_ia      PRIMARY KEY (id),
    CONSTRAINT uq_compartido_ia_dest UNIQUE (material_id, remitente_id, destinatario_id),
    CONSTRAINT fk_comp_ia_material   FOREIGN KEY (material_id)     REFERENCES MATERIAL_IA (id) ON DELETE CASCADE,
    CONSTRAINT fk_comp_ia_remitente  FOREIGN KEY (remitente_id)    REFERENCES USUARIO (id)     ON DELETE CASCADE,
    CONSTRAINT fk_comp_ia_dest       FOREIGN KEY (destinatario_id) REFERENCES USUARIO (id)     ON DELETE CASCADE
);

CREATE INDEX idx_comp_ia_dest_fecha ON COMPARTIDO_IA (destinatario_id, fecha_compartido DESC);
