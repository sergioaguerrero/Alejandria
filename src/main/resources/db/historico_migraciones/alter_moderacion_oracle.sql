-- 1. Estado de suspensión en USUARIO
ALTER TABLE USUARIO ADD (
    suspendido NUMBER(1, 0) DEFAULT 0 NOT NULL
);

ALTER TABLE USUARIO ADD CONSTRAINT chk_usuario_suspendido
    CHECK (suspendido IN (0, 1));

-- 2. Permitir estado HIDDEN en RECURSO_ACADEMICO
ALTER TABLE RECURSO_ACADEMICO DROP CONSTRAINT chk_recurso_estado;
ALTER TABLE RECURSO_ACADEMICO ADD CONSTRAINT chk_recurso_estado
    CHECK (estado IN ('PENDING', 'PUBLISHED', 'REPORTED', 'HIDDEN', 'REMOVED'));

-- 3. Ampliar REPORTE para soportar reportes a documentos, repositorios y perfiles
ALTER TABLE REPORTE MODIFY (
    recurso_id NUMBER(19, 0) NULL
);

ALTER TABLE REPORTE ADD (
    tipo_objetivo       VARCHAR2(20 CHAR)  DEFAULT 'DOCUMENT' NOT NULL,
    etiqueta_objetivo   VARCHAR2(255 CHAR),
    repositorio_id      NUMBER(19, 0),
    usuario_objetivo_id NUMBER(19, 0)
);

ALTER TABLE REPORTE ADD CONSTRAINT chk_reporte_tipo_obj
    CHECK (tipo_objetivo IN ('DOCUMENT', 'REPOSITORY', 'PROFILE'));

ALTER TABLE REPORTE DROP CONSTRAINT chk_reporte_motivo;
ALTER TABLE REPORTE ADD CONSTRAINT chk_reporte_motivo
    CHECK (motivo IN (
        'ACTIVE_EXAM', 'PLAGIARISM', 'INAPPROPRIATE_CONTENT',
        'CORRUPTED_FILE', 'MISLABELED', 'DUPLICATE', 'OTHER'
    ));

ALTER TABLE REPORTE ADD CONSTRAINT fk_reporte_repositorio
    FOREIGN KEY (repositorio_id) REFERENCES REPOSITORIO_ESTUDIO (id) ON DELETE SET NULL;

ALTER TABLE REPORTE ADD CONSTRAINT fk_reporte_usuario_obj
    FOREIGN KEY (usuario_objetivo_id) REFERENCES USUARIO (id) ON DELETE SET NULL;

CREATE INDEX idx_reporte_repositorio ON REPORTE (repositorio_id);
CREATE INDEX idx_reporte_usuario_obj ON REPORTE (usuario_objetivo_id);

-- 4. Ampliar DECISION para acción HIDE ('ocultado') y nota opcional
ALTER TABLE DECISION MODIFY (
    justificacion VARCHAR2(1000 CHAR) NULL
);

ALTER TABLE DECISION DROP CONSTRAINT chk_decision_accion;
ALTER TABLE DECISION ADD CONSTRAINT chk_decision_accion
    CHECK (accion_moderacion IN ('KEEP', 'HIDE', 'REMOVE', 'WARN_USER', 'SUSPEND_USER'));

-- 5. Historial de sanciones (advertencias, suspensiones y reactivaciones)
CREATE TABLE SANCION_USUARIO (
    id             NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id     NUMBER(19, 0)                      NOT NULL,
    moderador_id   NUMBER(19, 0)                      NOT NULL,
    reporte_id     NUMBER(19, 0),
    tipo           VARCHAR2(20 CHAR)                  NOT NULL,
    motivo         VARCHAR2(300 CHAR)                 NOT NULL,
    nota           VARCHAR2(1000 CHAR),
    fecha_creacion TIMESTAMP(6)  DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_sancion_usuario    PRIMARY KEY (id),
    CONSTRAINT chk_sancion_tipo      CHECK (tipo IN ('ADVERTENCIA', 'SUSPENSION', 'REACTIVACION')),
    CONSTRAINT fk_sancion_usuario    FOREIGN KEY (usuario_id)   REFERENCES USUARIO (id) ON DELETE CASCADE,
    CONSTRAINT fk_sancion_moderador  FOREIGN KEY (moderador_id) REFERENCES USUARIO (id),
    CONSTRAINT fk_sancion_reporte    FOREIGN KEY (reporte_id)   REFERENCES REPORTE (id) ON DELETE SET NULL
);

CREATE INDEX idx_sancion_usuario_fecha ON SANCION_USUARIO (usuario_id, fecha_creacion DESC);
