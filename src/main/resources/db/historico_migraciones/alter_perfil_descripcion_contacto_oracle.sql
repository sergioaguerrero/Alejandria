-- 1. Descripción / biografía opcional en USUARIO
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'USUARIO'
      AND COLUMN_NAME = 'DESCRIPCION';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE USUARIO ADD (descripcion VARCHAR2(500 CHAR))';
    END IF;
END;
/

-- 2. Medios de contacto configurables por el usuario
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM USER_TABLES
    WHERE TABLE_NAME = 'CONTACTO_USUARIO';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE CONTACTO_USUARIO (
                id         NUMBER(19, 0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                usuario_id NUMBER(19, 0)                      NOT NULL,
                tipo       VARCHAR2(30 CHAR)                  NOT NULL,
                valor      VARCHAR2(255 CHAR)                 NOT NULL,
                etiqueta   VARCHAR2(60 CHAR),
                orden      NUMBER(10, 0)     DEFAULT 0        NOT NULL,
                CONSTRAINT pk_contacto_usuario PRIMARY KEY (id),
                CONSTRAINT chk_contacto_tipo   CHECK (tipo IN (
                    ''EMAIL'', ''WHATSAPP'', ''INSTAGRAM'', ''LINKEDIN'', ''GITHUB'', ''TELEGRAM'', ''DISCORD'', ''WEBSITE'', ''OTHER''
                )),
                CONSTRAINT fk_contacto_usuario FOREIGN KEY (usuario_id) REFERENCES USUARIO (id) ON DELETE CASCADE
            )
        ';
    END IF;
END;
/

DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO v_count
    FROM USER_INDEXES
    WHERE INDEX_NAME = 'IDX_CONTACTO_USUARIO';

    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX idx_contacto_usuario ON CONTACTO_USUARIO (usuario_id, orden)';
    END IF;
END;
/
