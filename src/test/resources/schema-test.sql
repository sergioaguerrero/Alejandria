DROP ALL OBJECTS;

CREATE TABLE ROL (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    CONSTRAINT pk_rol        PRIMARY KEY (id),
    CONSTRAINT uq_rol_nombre UNIQUE (nombre)
);

CREATE TABLE PERMISO_ROL (
    rol_id  BIGINT       NOT NULL,
    permiso VARCHAR(100) NOT NULL,
    CONSTRAINT pk_permiso_rol     PRIMARY KEY (rol_id, permiso),
    CONSTRAINT fk_permiso_rol_rol FOREIGN KEY (rol_id) REFERENCES ROL (id) ON DELETE CASCADE
);

CREATE TABLE USUARIO (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_usuario       VARCHAR(150)                      NOT NULL,
    primer_nombre        VARCHAR(150)                      NOT NULL,
    segundo_nombre       VARCHAR(150),
    primer_apellido      VARCHAR(150)                      NOT NULL,
    segundo_apellido     VARCHAR(150)                      NOT NULL,
    correo_institucional VARCHAR(150)                      NOT NULL,
    contrasena_hash      VARCHAR(150)                      NOT NULL,
    verificado           INTEGER      DEFAULT 0            NOT NULL,
    fecha_registro       TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    semestre             INTEGER,
    rol_id               BIGINT,
    CONSTRAINT pk_usuario             PRIMARY KEY (id),
    CONSTRAINT uq_usuario_nombre      UNIQUE (nombre_usuario),
    CONSTRAINT uq_usuario_correo      UNIQUE (correo_institucional),
    CONSTRAINT chk_usuario_verificado CHECK (verificado IN (0, 1)),
    CONSTRAINT fk_usuario_rol         FOREIGN KEY (rol_id) REFERENCES ROL (id)
);

CREATE INDEX idx_usuario_rol ON USUARIO (rol_id);

CREATE TABLE CODIGO_VERIFICACION_CORREO (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    usuario_id       BIGINT                NOT NULL,
    codigo_hash      VARCHAR(128)          NOT NULL,
    fecha_creacion   TIMESTAMP(6)          NOT NULL,
    fecha_expiracion TIMESTAMP(6)          NOT NULL,
    intentos         INTEGER DEFAULT 0     NOT NULL,
    usado            INTEGER DEFAULT 0     NOT NULL,
    CONSTRAINT pk_codigo_verificacion PRIMARY KEY (id),
    CONSTRAINT chk_cvc_usado          CHECK (usado IN (0, 1)),
    CONSTRAINT fk_cvc_usuario         FOREIGN KEY (usuario_id) REFERENCES USUARIO (id) ON DELETE CASCADE
);

CREATE INDEX idx_cvc_usuario_usado    ON CODIGO_VERIFICACION_CORREO (usuario_id, usado);
CREATE INDEX idx_cvc_fecha_expiracion ON CODIGO_VERIFICACION_CORREO (fecha_expiracion);

CREATE TABLE FACULTAD (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    CONSTRAINT pk_facultad PRIMARY KEY (id)
);

CREATE TABLE PROGRAMA (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre      VARCHAR(150) NOT NULL,
    facultad_id BIGINT       NOT NULL,
    CONSTRAINT pk_programa          PRIMARY KEY (id),
    CONSTRAINT fk_programa_facultad FOREIGN KEY (facultad_id) REFERENCES FACULTAD (id)
);

CREATE INDEX idx_programa_facultad ON PROGRAMA (facultad_id);

CREATE TABLE SEMESTRE (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    numero_semestre INTEGER NOT NULL,
    programa_id     BIGINT  NOT NULL,
    CONSTRAINT pk_semestre          PRIMARY KEY (id),
    CONSTRAINT fk_semestre_programa FOREIGN KEY (programa_id) REFERENCES PROGRAMA (id)
);

CREATE INDEX idx_semestre_programa ON SEMESTRE (programa_id);

CREATE TABLE MATERIA (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo      VARCHAR(150) NOT NULL,
    nombre      VARCHAR(150) NOT NULL,
    creditos    INTEGER      NOT NULL,
    semestre_id BIGINT       NOT NULL,
    CONSTRAINT pk_materia          PRIMARY KEY (id),
    CONSTRAINT fk_materia_semestre FOREIGN KEY (semestre_id) REFERENCES SEMESTRE (id)
);

CREATE INDEX idx_materia_semestre ON MATERIA (semestre_id);

CREATE TABLE REPOSITORIO_ESTUDIO (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre              VARCHAR(200)                      NOT NULL,
    descripcion         VARCHAR(2000),
    materia_id          BIGINT                            NOT NULL,
    usuario_id          BIGINT                            NOT NULL,
    total_me_gusta      INTEGER      DEFAULT 0            NOT NULL,
    fecha_creacion      TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_repositorio_estudio PRIMARY KEY (id),
    CONSTRAINT fk_repo_materia        FOREIGN KEY (materia_id) REFERENCES MATERIA (id),
    CONSTRAINT fk_repo_usuario        FOREIGN KEY (usuario_id) REFERENCES USUARIO (id)
);

CREATE INDEX idx_repo_materia        ON REPOSITORIO_ESTUDIO (materia_id);
CREATE INDEX idx_repo_usuario        ON REPOSITORIO_ESTUDIO (usuario_id);
CREATE INDEX idx_repo_fecha_creacion ON REPOSITORIO_ESTUDIO (fecha_creacion);

CREATE TABLE ME_GUSTA_REPOSITORIO (
    repositorio_id BIGINT                            NOT NULL,
    usuario_id     BIGINT                            NOT NULL,
    fecha_registro TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_me_gusta_repo       PRIMARY KEY (repositorio_id, usuario_id),
    CONSTRAINT fk_mg_repo_repositorio FOREIGN KEY (repositorio_id) REFERENCES REPOSITORIO_ESTUDIO (id) ON DELETE CASCADE,
    CONSTRAINT fk_mg_repo_usuario     FOREIGN KEY (usuario_id)     REFERENCES USUARIO (id)             ON DELETE CASCADE
);

CREATE INDEX idx_mg_repo_usuario ON ME_GUSTA_REPOSITORIO (usuario_id);

CREATE TABLE SEGUIMIENTO_REPOSITORIO (
    repositorio_id BIGINT                            NOT NULL,
    usuario_id     BIGINT                            NOT NULL,
    fecha_registro TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT pk_seguimiento_repo     PRIMARY KEY (repositorio_id, usuario_id),
    CONSTRAINT fk_seg_repo_repositorio FOREIGN KEY (repositorio_id) REFERENCES REPOSITORIO_ESTUDIO (id) ON DELETE CASCADE,
    CONSTRAINT fk_seg_repo_usuario     FOREIGN KEY (usuario_id)     REFERENCES USUARIO (id)             ON DELETE CASCADE
);

CREATE INDEX idx_seg_repo_usuario ON SEGUIMIENTO_REPOSITORIO (usuario_id);

CREATE TABLE RECURSO_ACADEMICO (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    titulo          VARCHAR(200)                      NOT NULL,
    descripcion     VARCHAR(2000),
    tipo_recurso    VARCHAR(20)                       NOT NULL,
    archivo_bytes   BLOB                              NOT NULL,
    tipo_mime       VARCHAR(100)                      NOT NULL,
    tamano_bytes    BIGINT                            NOT NULL,
    fecha_subida    TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    estado          VARCHAR(20)                       NOT NULL,
    total_descargas INTEGER      DEFAULT 0            NOT NULL,
    subido_por      BIGINT                            NOT NULL,
    materia_id      BIGINT                            NOT NULL,
    repositorio_id  BIGINT,
    CONSTRAINT pk_recurso_academico  PRIMARY KEY (id),
    CONSTRAINT chk_recurso_tipo      CHECK (tipo_recurso IN ('NOTE', 'SUMMARY', 'GUIDE', 'WORKSHOP', 'PROJECT')),
    CONSTRAINT chk_recurso_estado    CHECK (estado IN ('PENDING', 'PUBLISHED', 'REPORTED', 'REMOVED')),
    CONSTRAINT fk_recurso_subido_por FOREIGN KEY (subido_por)     REFERENCES USUARIO (id),
    CONSTRAINT fk_recurso_materia    FOREIGN KEY (materia_id)     REFERENCES MATERIA (id),
    CONSTRAINT fk_recurso_repositorio FOREIGN KEY (repositorio_id) REFERENCES REPOSITORIO_ESTUDIO (id) ON DELETE CASCADE
);

CREATE INDEX idx_recurso_subido_por  ON RECURSO_ACADEMICO (subido_por);
CREATE INDEX idx_recurso_materia     ON RECURSO_ACADEMICO (materia_id);
CREATE INDEX idx_recurso_repositorio ON RECURSO_ACADEMICO (repositorio_id);

CREATE TABLE ETIQUETA (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre VARCHAR(60) NOT NULL,
    CONSTRAINT pk_etiqueta        PRIMARY KEY (id),
    CONSTRAINT uq_etiqueta_nombre UNIQUE (nombre)
);

CREATE TABLE RECURSO_ETIQUETA (
    recurso_id  BIGINT NOT NULL,
    etiqueta_id BIGINT NOT NULL,
    CONSTRAINT pk_recurso_etiqueta  PRIMARY KEY (recurso_id, etiqueta_id),
    CONSTRAINT fk_rec_etiq_recurso  FOREIGN KEY (recurso_id)  REFERENCES RECURSO_ACADEMICO (id) ON DELETE CASCADE,
    CONSTRAINT fk_rec_etiq_etiqueta FOREIGN KEY (etiqueta_id) REFERENCES ETIQUETA (id)          ON DELETE CASCADE
);

CREATE INDEX idx_rec_etiq_etiqueta ON RECURSO_ETIQUETA (etiqueta_id);

CREATE TABLE CALIFICACION (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    puntuacion         INTEGER                        NOT NULL,
    texto_comentario   VARCHAR(1000),
    fecha_calificacion TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    usuario_id         BIGINT                         NOT NULL,
    recurso_id         BIGINT                         NOT NULL,
    CONSTRAINT pk_calificacion       PRIMARY KEY (id),
    CONSTRAINT chk_calificacion_punt CHECK (puntuacion BETWEEN 1 AND 5),
    CONSTRAINT uq_calif_usuario_rec  UNIQUE (usuario_id, recurso_id),
    CONSTRAINT fk_calif_usuario      FOREIGN KEY (usuario_id) REFERENCES USUARIO (id),
    CONSTRAINT fk_calif_recurso      FOREIGN KEY (recurso_id) REFERENCES RECURSO_ACADEMICO (id) ON DELETE CASCADE
);

CREATE INDEX idx_calif_recurso ON CALIFICACION (recurso_id);

CREATE TABLE REPORTE (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    motivo        VARCHAR(30)                       NOT NULL,
    descripcion   VARCHAR(1000),
    fecha_reporte TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    estado        VARCHAR(20)                       NOT NULL,
    reportante_id BIGINT                            NOT NULL,
    recurso_id    BIGINT                            NOT NULL,
    moderador_id  BIGINT,
    CONSTRAINT pk_reporte            PRIMARY KEY (id),
    CONSTRAINT chk_reporte_motivo    CHECK (motivo IN ('ACTIVE_EXAM', 'PLAGIARISM', 'INAPPROPRIATE_CONTENT', 'CORRUPTED_FILE', 'OTHER')),
    CONSTRAINT chk_reporte_estado    CHECK (estado IN ('OPEN', 'UNDER_REVIEW', 'RESOLVED', 'DISMISSED')),
    CONSTRAINT fk_reporte_reportante FOREIGN KEY (reportante_id) REFERENCES USUARIO (id),
    CONSTRAINT fk_reporte_recurso    FOREIGN KEY (recurso_id)    REFERENCES RECURSO_ACADEMICO (id),
    CONSTRAINT fk_reporte_moderador  FOREIGN KEY (moderador_id)  REFERENCES USUARIO (id)
);

CREATE INDEX idx_reporte_estado     ON REPORTE (estado);
CREATE INDEX idx_reporte_recurso    ON REPORTE (recurso_id);
CREATE INDEX idx_reporte_reportante ON REPORTE (reportante_id);
CREATE INDEX idx_reporte_moderador  ON REPORTE (moderador_id);

CREATE TABLE DECISION (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    accion_moderacion VARCHAR(30)                       NOT NULL,
    justificacion     VARCHAR(1000)                     NOT NULL,
    fecha_decision    TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    reporte_id        BIGINT                            NOT NULL,
    moderador_id      BIGINT                            NOT NULL,
    CONSTRAINT pk_decision           PRIMARY KEY (id),
    CONSTRAINT uq_decision_reporte   UNIQUE (reporte_id),
    CONSTRAINT chk_decision_accion   CHECK (accion_moderacion IN ('KEEP', 'REMOVE', 'WARN_USER', 'SUSPEND_USER')),
    CONSTRAINT fk_decision_reporte   FOREIGN KEY (reporte_id)   REFERENCES REPORTE (id),
    CONSTRAINT fk_decision_moderador FOREIGN KEY (moderador_id) REFERENCES USUARIO (id)
);

CREATE INDEX idx_decision_moderador ON DECISION (moderador_id);

CREATE TABLE REGISTRO_AUDITORIA (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_accion  VARCHAR(100)                      NOT NULL,
    nombre_entidad VARCHAR(100)                      NOT NULL,
    entidad_id     BIGINT,
    fecha_evento   TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    ip_origen      VARCHAR(45),
    usuario_id     BIGINT,
    CONSTRAINT pk_registro_auditoria PRIMARY KEY (id),
    CONSTRAINT fk_auditoria_usuario  FOREIGN KEY (usuario_id) REFERENCES USUARIO (id)
);

CREATE INDEX idx_auditoria_usuario ON REGISTRO_AUDITORIA (usuario_id);
CREATE INDEX idx_auditoria_entidad ON REGISTRO_AUDITORIA (nombre_entidad, entidad_id);

CREATE TABLE INTERACCION (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tipo_interaccion   VARCHAR(20)                       NOT NULL,
    fecha_interaccion  TIMESTAMP(6) DEFAULT LOCALTIMESTAMP NOT NULL,
    termino_busqueda   VARCHAR(200),
    usuario_anonimo_id VARCHAR(64)                       NOT NULL,
    usuario_id         BIGINT,
    recurso_id         BIGINT,
    materia_id         BIGINT,
    CONSTRAINT pk_interaccion         PRIMARY KEY (id),
    CONSTRAINT chk_interaccion_tipo   CHECK (tipo_interaccion IN ('VIEW', 'DOWNLOAD', 'SEARCH', 'RATING')),
    CONSTRAINT fk_interaccion_usuario FOREIGN KEY (usuario_id) REFERENCES USUARIO (id),
    CONSTRAINT fk_interaccion_recurso FOREIGN KEY (recurso_id) REFERENCES RECURSO_ACADEMICO (id),
    CONSTRAINT fk_interaccion_materia FOREIGN KEY (materia_id) REFERENCES MATERIA (id)
);

CREATE INDEX idx_interaccion_fecha    ON INTERACCION (fecha_interaccion);
CREATE INDEX idx_interaccion_mat_tipo ON INTERACCION (materia_id, tipo_interaccion);
CREATE INDEX idx_interaccion_recurso  ON INTERACCION (recurso_id);
CREATE INDEX idx_interaccion_usuario  ON INTERACCION (usuario_id);

CREATE TABLE METRICA_DEMANDA (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    periodo_academico VARCHAR(10)       NOT NULL,
    total_consultas   INTEGER DEFAULT 0 NOT NULL,
    total_descargas   INTEGER DEFAULT 0 NOT NULL,
    total_busquedas   INTEGER DEFAULT 0 NOT NULL,
    indice_demanda    FLOAT(53) DEFAULT 0 NOT NULL,
    materia_id        BIGINT            NOT NULL,
    CONSTRAINT pk_metrica_demanda     PRIMARY KEY (id),
    CONSTRAINT uq_metrica_mat_periodo UNIQUE (materia_id, periodo_academico),
    CONSTRAINT fk_metrica_materia     FOREIGN KEY (materia_id) REFERENCES MATERIA (id)
);
